package misetoml_test

import (
	"bufio"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/Tomy-ch/terraform-aws-boilerplate/scripts/lib/misetoml"
)

// soundLock は mise lock が書く形の lock。go: の道具は platform を持たず、platform は url_api と provenance も持つ。
const soundLock = `# @generated - this file is auto-generated by ` + "`mise lock`" + `

lockfile_version = 3

[[tools.actionlint]]
version = "1.7.12"
backend = "aqua:rhysd/actionlint"
specifiers = ["1.7.12"]

[tools.actionlint."platforms.linux-x64"]
checksum = "sha256:aaa"
url = "https://github.com/rhysd/actionlint/releases/download/v1.7.12/actionlint_1.7.12_linux_amd64.tar.gz"
url_api = "https://api.github.com/repos/rhysd/actionlint/releases/assets/1"
provenance = "github-attestations"

[[tools."go:golang.org/x/vuln/cmd/govulncheck"]]
version = "1.10.0"
backend = "go:golang.org/x/vuln/cmd/govulncheck"
specifiers = ["1.10.0"]
`

func TestParseLock(t *testing.T) {
	t.Parallel()

	t.Run("正常系", func(t *testing.T) {
		t.Parallel()

		t.Run("道具ごとの版・backend・platform の url と照合値を、書かれた順で返す", func(t *testing.T) {
			t.Parallel()

			got, err := misetoml.ParseLock([]byte(soundLock))

			require.NoError(t, err)
			assert.Equal(t, []misetoml.LockEntry{
				{
					Key: "actionlint", Version: "1.7.12", Backend: "aqua:rhysd/actionlint",
					Platforms: map[string]misetoml.LockPlatform{"linux-x64": {
						URL:      "https://github.com/rhysd/actionlint/releases/download/v1.7.12/actionlint_1.7.12_linux_amd64.tar.gz",
						Checksum: "sha256:aaa",
					}},
				},
				{
					Key: "go:golang.org/x/vuln/cmd/govulncheck", Version: "1.10.0", Backend: "go:golang.org/x/vuln/cmd/govulncheck",
					Platforms: map[string]misetoml.LockPlatform{},
				},
			}, got)
		})
	})

	t.Run("異常系", func(t *testing.T) {
		t.Parallel()

		tests := map[string]struct{ content, say string }{
			"lockfile_version が無い":    {"[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n", "lockfile_version がありません"},
			"空の入力":                    {"", "lockfile_version がありません"},
			"lockfile_version が2つある":  {"lockfile_version = 3\nlockfile_version = 3\n", "2行目"},
			"読めない lockfile_version":   {"lockfile_version = 99\n", "読める lockfile_version は 3 だけです"},
			"道具の entry の前に知らない行がある":   {"lockfile_version = 3\nfoo = 1\n", "2行目"},
			"同じ道具の entry が2つある":       {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[[tools.a]]\nversion = \"2\"\nbackend = \"aqua:o/a\"\n", "道具の entry の重複"},
			"entry に知らない文字列の key がある": {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\noptions = \"x\"\nbackend = \"aqua:o/a\"\n", "知らない key options"},
			"entry に文字列でない値の行がある":     {"lockfile_version = 3\n[[tools.\"npm:a\"]]\nversion = \"1\"\naube = { path = \".mise/locks/npm-a/1\" }\nbackend = \"npm:a\"\n", "4行目"},
			"platform に知らない key がある":  {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nsize = \"1\"\n", "知らない key size"},
			"platform の中に配列がある":       {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nspecifiers = [\"1\"]\n", "6行目"},
			"別の道具の platform が混ざる":     {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.b.\"platforms.linux-x64\"]\nurl = \"https://example.com\"\n", "道具の entry の外の platform"},
			"entry の外に platform がある":  {"lockfile_version = 3\n[tools.a.\"platforms.linux-x64\"]\n", "道具の entry の外の platform"},
			"同じ platform が2つある":       {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nurl = \"https://example.com/1\"\n[tools.a.\"platforms.linux-x64\"]\n", "platform の重複"},
			"version が2つある":           {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\nversion = \"2\"\n", "version の重複"},
			"backend が2つある":           {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\nbackend = \"aqua:o/b\"\n", "backend の重複"},
			"url が2つある":               {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nurl = \"https://example.com/1\"\nurl = \"https://example.com/2\"\n", "url の重複"},
			"checksum が2つある":          {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nchecksum = \"sha256:a\"\nchecksum = \"sha256:b\"\n", "checksum の重複"},
			"version が無い":             {"lockfile_version = 3\n[[tools.a]]\nbackend = \"aqua:o/a\"\n", "version か backend がありません"},
			"backend が無い":             {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\n", "version か backend がありません"},
			"entry に文字列でない値がある":       {"lockfile_version = 3\n[[tools.a]]\nversion = 1\nbackend = \"aqua:o/a\"\n", "3行目"},
			"platform に文字列でない値がある":    {"lockfile_version = 3\n[[tools.a]]\nversion = \"1\"\nbackend = \"aqua:o/a\"\n[tools.a.\"platforms.linux-x64\"]\nurl = 1\n", "6行目"},
		}
		for name, tt := range tests {
			t.Run(name+"場合、ErrInvalidLock で理由を名指す", func(t *testing.T) {
				t.Parallel()

				got, err := misetoml.ParseLock([]byte(tt.content))

				require.ErrorIs(t, err, misetoml.ErrInvalidLock)
				assert.Contains(t, err.Error(), tt.say)
				assert.Nil(t, got)
			})
		}
	})

	t.Run("bufio の上限を超える1行は、走査のエラーで落ちる", func(t *testing.T) {
		t.Parallel()

		got, err := misetoml.ParseLock([]byte("lockfile_version = 3\n# " + strings.Repeat("x", 70*1024) + "\n"))

		require.ErrorIs(t, err, bufio.ErrTooLong)
		assert.Nil(t, got)
	})
}

func TestParseLockFile(t *testing.T) {
	t.Parallel()

	t.Run("ファイルを読んで ParseLock の結果を返す", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), misetoml.LockFile)
		require.NoError(t, os.WriteFile(path, []byte(soundLock), 0o600))

		got, err := misetoml.ParseLockFile(path)

		require.NoError(t, err)
		assert.Len(t, got, 2)
	})

	t.Run("読めないファイルはエラーで、path を添える", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), misetoml.LockFile)

		_, err := misetoml.ParseLockFile(path)

		require.ErrorIs(t, err, os.ErrNotExist)
		assert.Contains(t, err.Error(), path)
	})

	t.Run("解釈できない内容は ErrInvalidLock で、path を添える", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), misetoml.LockFile)
		require.NoError(t, os.WriteFile(path, []byte("x = 1\n"), 0o600))

		_, err := misetoml.ParseLockFile(path)

		require.ErrorIs(t, err, misetoml.ErrInvalidLock)
		assert.Contains(t, err.Error(), path)
	})
}

func TestLockfilePlatforms(t *testing.T) {
	t.Parallel()

	t.Run("[settings] の lockfile_platforms を書かれた順で返す", func(t *testing.T) {
		t.Parallel()

		got, found, err := misetoml.LockfilePlatforms([]byte("[tools]\ngo = \"1\"\n\n[settings]\nlockfile_platforms = [\"linux-x64\", \"macos-arm64\"]\n"))

		require.NoError(t, err)
		assert.True(t, found)
		assert.Equal(t, []string{"linux-x64", "macos-arm64"}, got)
	})

	t.Run("宣言が無ければ found が false", func(t *testing.T) {
		t.Parallel()

		got, found, err := misetoml.LockfilePlatforms([]byte("[settings]\ndisable_tools = []\n"))

		require.NoError(t, err)
		assert.False(t, found)
		assert.Nil(t, got)
	})

	t.Run("[tools] の中の同名のキーは読まない", func(t *testing.T) {
		t.Parallel()

		_, found, err := misetoml.LockfilePlatforms([]byte("[tools]\nlockfile_platforms = \"x\"\n"))

		require.NoError(t, err)
		assert.False(t, found)
	})

	t.Run("読めない宣言は ErrInvalidLockfilePlatforms", func(t *testing.T) {
		t.Parallel()

		_, _, err := misetoml.LockfilePlatforms([]byte("[settings]\nlockfile_platforms = [\n  \"linux-x64\",\n]\n"))

		require.ErrorIs(t, err, misetoml.ErrInvalidLockfilePlatforms)
	})
}

func TestLockfilePlatformsFile(t *testing.T) {
	t.Parallel()

	t.Run("ファイルを読んで LockfilePlatforms の結果を返す", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), "mise.toml")
		require.NoError(t, os.WriteFile(path, []byte("[settings]\nlockfile_platforms = [\"linux-x64\"]\n"), 0o600))

		got, found, err := misetoml.LockfilePlatformsFile(path)

		require.NoError(t, err)
		assert.True(t, found)
		assert.Equal(t, []string{"linux-x64"}, got)
	})

	t.Run("読めないファイルはエラーで、path を添える", func(t *testing.T) {
		t.Parallel()
		path := filepath.Join(t.TempDir(), "mise.toml")

		_, _, err := misetoml.LockfilePlatformsFile(path)

		require.ErrorIs(t, err, os.ErrNotExist)
		assert.Contains(t, err.Error(), path)
	})
}
